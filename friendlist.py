def showlist():
    os.system("cls")
    amt = len(friends)
    if amt == 0:
        load()
        print("No friends added.")
        time.sleep(1)
        os.system("cls")
        return
    else:
        load()
        time.sleep(0.5)
        print(f"You have {str(amt)} friends.")
        for item in friends:
            onlcheck = random.choice(onl)
            print(f"- {item}: {onlcheck}")
        time.sleep(5)
        os.system("cls")

def remfriend():
    os.system("cls")
    amt = len(friends)
    if amt == 0:
        load()
        time.sleep(0.5)
        print(" < [NO FRIENDS ADDED] >")
        time.sleep(1)
        os.system("cls")
        return
    remofriend = input("Who do you want to remove from your friendlist?   < ")
    if remofriend not in friends:
        load()
        time.sleep(0.5)
        print("Friend is not in your Friendlist.")
        time.sleep(1)
        os.system("cls")
        return

    else:
        load()
        time.sleep(0.5)
        friends.discard(remofriend)
        print(f"{remofriend} is removed from your friendlist.")
        time.sleep(1)
        os.system("cls")

